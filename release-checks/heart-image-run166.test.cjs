'use strict';
/* RUN166: additive verified anatomy labels and one static picture, no user state. */
const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict'),crypto=require('crypto');
const read=p=>fs.readFileSync(p,'utf8');
const ctx=vm.createContext({window:{}});
vm.runInContext(read('data.js'),ctx);
const old=ctx.window.RS_DATA.terms.map(x=>({id:x.id,fi:x.fi,ru:x.ru}));
assert.equal(old.length,1296);
vm.runInContext(read('riveria-anatomy-exam.js'),ctx);
const d=ctx.window.RS_DATA;
assert.equal(d.terms.length,1457,'previous 1446 unique public terms + 11 RUN166 records');
assert.equal(d.examTopics.length,10);
const byId=new Map(d.terms.map(x=>[x.id,x]));
const norms=d.terms.map(x=>x.fi.toLocaleLowerCase('fi').trim());
assert.equal(byId.size,d.terms.length,'all progress IDs must remain stable and unique');
assert.equal(new Set(norms).size,norms.length,'one FI entry per structure');
old.forEach(x=>{const item=byId.get(x.id);assert.ok(item,'original word missing: '+x.id);assert.equal(item.fi,x.fi);assert.equal(item.ru,x.ru);});
const oldHeartIds=['T90226','T01122','T01121','T90232','T01077','T01119','T01114','T01115','T01116','T01117'];
const newFIs=['nouseva aortta','arteriekartio','papillaarilihas','aortankaari','keuhkovaltimorunko','vasen keuhkovaltimo','eteisväliseinä','vasemmat keuhkolaskimot','jännerihmat','kammioiden väliseinä','lihapalkit'];
const newIds=newFIs.map((fi,i)=>'T'+(90305+i));
const imageIds=oldHeartIds.concat(newIds,['T00574']);
assert.equal(imageIds.length,22);
imageIds.forEach(id=>{const x=byId.get(id);assert.ok(x,'missing linked ID '+id);assert.ok(x.fi&&x.ru&&x.en&&x.la,'missing translations or Latin: '+id);
  assert.ok(x.examNoteFi&&x.examNoteFi.length>=40,'FI note too short '+id);assert.ok(x.examNoteRu&&x.examNoteRu.length>=40,'RU note too short '+id);
  assert.ok(x.examTopics.includes('EXAM05'),'must be in existing Verenkierto exam topic: '+id);
});
newFIs.forEach((fi,i)=>assert.equal(byId.get(newIds[i]).fi,fi));
assert.ok(byId.get('T01077').examTopics.includes('EXAM08'),'previous urinary-topic membership lost');
assert.equal(d.terms.filter(x=>x.fi==='sydämen väliseinä').length,1,'do not merge separate atrial and ventricular structures');
const app=read('app.js'),css=read('style.css'),html=read('index.html'),sw=read('sw.js');
imageIds.forEach(id=>assert.match(app,new RegExp('\\b'+id+':1\\b|\\b'+id+':1,'),'image ID mapping missing: '+id));
assert.ok(app.includes("if(state.flipped){")&&app.includes("heartIllustration(c)+examNote(c)"),'the picture must be after reveal and before explanations');
assert.ok(app.includes("heartIllustration(q.item)+examNote(q.item)"),'the 4-choice quiz must show the picture only after grading');
assert.ok(app.includes('heartSetScale')&&app.includes('touchmove')&&app.includes('data-heart-control'),'image zoom missing');
assert.ok(css.includes('.rs-heart-modal')&&css.includes('.rs-heart-image'));
const heartRev='heart-run166-1',appRev='exam-preserve-run167-1',cache='riveria-sanasto-community-v3.0.0-rc35',picture='assets/anatomy/heart-section-fi.jpg';
[['app.js',appRev],['riveria-anatomy-exam.js',heartRev],['style.css',heartRev]].forEach(pair=>{const p=pair[0],rev=pair[1];assert.ok(html.includes(p+'?v='+rev),p+' HTML revision');assert.ok(sw.includes(p+'?v='+rev),p+' offline revision');});
assert.ok(sw.includes(cache)&&sw.includes(picture)&&app.includes(picture),'offline image path and new cache required');
assert.ok(fs.existsSync(picture),'Production heart JPEG missing — upload the provided generated image to assets/anatomy/heart-section-fi.jpg before merge');
const buf=fs.readFileSync(picture);
assert.ok(buf.length>100000&&buf[0]===255&&buf[1]===216,'expected legible real JPEG image, not placeholder');
const actual=crypto.createHash('sha256').update(buf).digest('hex');
assert.equal(actual,'8f35e7e90ab70d284826efeaa272398068ba7ceaae6ce932f72fd069e3db1a96','heart diagram image differs from owner-approved source');
console.log('PASS RUN166: 11 new words, 22 image-enabled IDs, unchanged earlier terms, 10 topics, genuine JPEG, zoom and cache.');
